#!/usr/bin/env node
/**
 * extract-review-text.js — build the native-speaker review dump (docs/21).
 *
 * Walks data/seed/**\/*.json (skipping _TEMPLATE/_ files), extracts every
 * ar / ckb / kmr string alongside its English reference, and prints a
 * Markdown checklist a native reviewer can work through in one sitting.
 *
 * Usage (from repo root):
 *   node content-kit/extract-review-text.js                       # print to stdout
 *   node content-kit/extract-review-text.js > content-kit/review-text.generated.md
 *
 * Offline, zero dependencies, ESM. Re-run after every seed-data change
 * (especially once the real seed-20 lands) to refresh the review pack.
 */

import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, dirname, resolve, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const SEED_DIR = resolve(__dirname, '..', 'data', 'seed');
const REVIEW_LANGS = ['ar', 'ckb', 'kmr'];
const LANG_LABELS = { ar: 'ar (Iraqi Arabic)', ckb: 'ckb (Sorani)', kmr: 'kmr (Badini/Kurmanji)' };

/** Recursively collect seed JSON files, skipping _-prefixed ones (ingestion skips them too). */
function collectFiles(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...collectFiles(p));
    else if (name.endsWith('.json') && !name.startsWith('_')) out.push(p);
  }
  return out.sort();
}

/** True when an object is a language map ({en, ar, ckb, kmr, ...} of strings or string-arrays). */
function isLangMap(v) {
  if (v === null || typeof v !== 'object' || Array.isArray(v)) return false;
  const keys = Object.keys(v);
  if (keys.length === 0) return false;
  const langKeys = ['en', ...REVIEW_LANGS];
  return keys.every(
    (k) =>
      langKeys.includes(k) &&
      (typeof v[k] === 'string' || (Array.isArray(v[k]) && v[k].every((x) => typeof x === 'string')))
  );
}

/** Walk an entity and yield {path, map} for every language map found. */
function findLangMaps(node, path = []) {
  const found = [];
  if (node === null || typeof node !== 'object') return found;
  if (isLangMap(node)) return [{ path: path.join('.'), map: node }];
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith('_')) continue;
    found.push(...findLangMaps(v, [...path, k]));
  }
  return found;
}

const md = [];
const files = collectFiles(SEED_DIR);
let stringCount = 0;

md.push('<!-- GENERATED by content-kit/extract-review-text.js — do not edit by hand. -->');
md.push(`<!-- Source: data/seed (${files.length} entities) · generated ${new Date().toISOString()} -->`);
md.push('');

for (const file of files) {
  const entity = JSON.parse(readFileSync(file, 'utf8'));
  const rel = file.slice(SEED_DIR.length + 1).replaceAll('\\', '/');
  const enName = entity.names?.en ?? basename(file, '.json');
  md.push(`## ${entity.entity_id ?? basename(file, '.json')} — ${enName}`);
  md.push('');
  md.push(`File: \`data/seed/${rel}\``);
  const note = entity.attributes?.review_note;
  if (note) md.push(`> Authoring note: ${note}`);
  md.push('');

  for (const { path, map } of findLangMaps(entity)) {
    const hasReviewText = REVIEW_LANGS.some((l) => map[l] && map[l].length > 0);
    if (!hasReviewText) continue;

    const en = map.en;
    md.push(`### \`${path}\``);
    if (typeof en === 'string') md.push(`English reference: "${en}"`);
    md.push('');
    for (const lang of REVIEW_LANGS) {
      const v = map[lang];
      if (v === undefined || v.length === 0) continue;
      const items = Array.isArray(v) ? v : [v];
      for (const s of items) {
        md.push(`- [ ] **${LANG_LABELS[lang]}**: ${s}`);
        stringCount++;
      }
    }
    md.push('');
  }
}

md.push('---');
md.push(`Total strings to review: **${stringCount}** across ${files.length} entities.`);
md.push('');

process.stdout.write(md.join('\n'));
